drop database if exists stock_exchange;
create database stock_exchange;
use stock_exchange;

create table Investors (
    investor_id int auto_increment primary key,
    full_name varchar(100) not null,
    email varchar(120) not null unique,
    password_hash varchar(255) not null,
    phone varchar(15),
    balance decimal(15,2) not null default 0,
    role enum('INVESTOR','ADMIN') not null default 'INVESTOR',
    created_at timestamp not null default current_timestamp,
    check (balance >= 0)
);

create table Companies (
    company_id int auto_increment primary key,
    company_name varchar(120) not null unique,
    sector varchar(60) not null,
    headquarters varchar(80),
    listed_date date not null
);

create table Stocks (
    stock_id int auto_increment primary key,
    company_id int not null unique,
    symbol varchar(10) not null unique,
    current_price decimal(10,2) not null,
    total_shares bigint not null,
    foreign key (company_id) references Companies(company_id) on delete cascade,
    check (current_price > 0),
    check (total_shares > 0)
);

create table Orders (
    order_id int auto_increment primary key,
    investor_id int not null,
    stock_id int not null,
    order_type enum('BUY','SELL') not null,
    quantity int not null,
    price decimal(10,2) not null,
    status enum('PENDING','EXECUTED','REJECTED','CANCELLED','FLAGGED') not null default 'PENDING',
    order_time timestamp not null default current_timestamp,
    foreign key (investor_id) references Investors(investor_id),
    foreign key (stock_id) references Stocks(stock_id),
    check (quantity > 0),
    check (price > 0)
);

create table Transactions (
    transaction_id int auto_increment primary key,
    order_id int not null unique,
    quantity int not null,
    price decimal(10,2) not null,
    total_amount decimal(15,2) generated always as (quantity * price) stored,
    is_flagged boolean not null default false,
    txn_time timestamp not null default current_timestamp,
    foreign key (order_id) references Orders(order_id),
    check (quantity > 0),
    check (price > 0)
);

create table Cashflows (
    cashflow_id int auto_increment primary key,
    investor_id int not null,
    flow_type enum('DEPOSIT','WITHDRAW') not null,
    amount decimal(15,2) not null,
    balance_after decimal(15,2) not null,
    note varchar(255),
    created_at timestamp not null default current_timestamp,
    foreign key (investor_id) references Investors(investor_id),
    check (amount > 0)
);

create table Portfolios (
    portfolio_id int auto_increment primary key,
    investor_id int not null,
    stock_id int not null,
    quantity int not null default 0,
    avg_buy_price decimal(10,2) not null default 0,
    unique (investor_id, stock_id),
    foreign key (investor_id) references Investors(investor_id),
    foreign key (stock_id) references Stocks(stock_id),
    check (quantity >= 0),
    check (avg_buy_price >= 0)
);

create table Price_History (
    history_id int auto_increment primary key,
    stock_id int not null,
    old_price decimal(10,2) not null,
    new_price decimal(10,2) not null,
    changed_at timestamp not null default current_timestamp,
    foreign key (stock_id) references Stocks(stock_id),
    check (old_price > 0),
    check (new_price > 0)
);

